/*
 * Four lanes are the two 4-pixel bands inside each LCD1602 character row.
 * The physical key order on the PuZhong board is K1, K2, K3, K4 from left
 * to right; the game deliberately maps lanes top-to-bottom to K4, K3, K2, K1
 * (P3.3, P3.2, P3.0, P3.1), as required by the hardware layout.
 *
 * `at` is a song-unit offset. Every offset below is the start of a real
 * non-rest note in songs.h; the second entry at selected offsets is a legal
 * upper/lower simultaneous pair.
 */
